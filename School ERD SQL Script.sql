CREATE DATABASE SCHOOL;
CREATE TABLE CLASS_SA (
CLASS_CODE_SA CHAR(2) PRIMARY KEY,
ROOM_NUMBER_SA CHAR(11),
PHONE_SA CHAR(11),
MAXIMUM_CAPACITY_SA DECIMAL(2),
DIRECTIONS_SA VARCHAR(140),
TEACHER_SA_ID_SA INT);
CREATE TABLE STUDENT_SA (
ID_SA INT PRIMARY KEY,
FIRST_NAME_SA VARCHAR(23),
MIDDLE_NAME_SA VARCHAR(23),
LAST_NAME_SA VARCHAR(23),
NICKNAME_SA VARCHAR(25),
DATE_OF_BIRTH_SA YEAR,
CLASS_CODE_SA CHAR(2),
CITY_SA VARCHAR(15),
ZIPCODE_SA CHAR(5),
STREET_SA VARCHAR(35));
CREATE TABLE CARETAKER_SA (
ID_SA INT PRIMARY KEY,
FIRST_NAME_SA VARCHAR(23),
MIDDLE_NAME_SA VARCHAR(23),
LAST_NAME_SA VARCHAR(23),
PHONE_SA CHAR(11),
EMAIL_SA VARCHAR(30),
RELATIONSHIP_SA VARCHAR(25));
CREATE TABLE TEACHER_SA (
ID_SA INT PRIMARY KEY,
FIRST_NAME_SA VARCHAR(23),
MIDDLE_NAME_SA VARCHAR(23), 
LAST_NAME_SA VARCHAR(23),
PHONE_SA CHAR(11),
EMAIL_SA VARCHAR(30),
GRADUATED_COLLEGE_SA VARCHAR(25),
HIGHEST_DEGREE_SA VARCHAR(5));
CREATE TABLE REGISTRATION_SA (
CARETAKER_ID_SA INT NOT NULL,
STUDENT_ID_SA INT NOT NULL,
CONSTRAINT REGISTRATION_PK_SA PRIMARY KEY (CARETAKER_ID_SA, STUDENT_ID_SA),
CONSTRAINT CARETAKER_ID_SA FOREIGN KEY (CARETAKER_ID_SA) REFERENCES CARETAKER_SA(ID_SA),
CONSTRAINT STUDENT_ID_SA FOREIGN KEY (STUDENT_ID_SA) REFERENCES STUDENT_SA(ID_SA));
