# Task 5 - Query the Data by Siya Acharya
SELECT STUDENT_SA.FIRST_NAME_SA AS Student,
STUDENT_SA.DATE_OF_BIRTH_SA AS Level,
CLASS_SA.DIRECTIONS_SA AS Directions,
TEACHER_SA.FIRST_NAME_SA AS Teacher
FROM STUDENT_SA
JOIN CLASS_SA ON STUDENT_SA.CLASS_CODE_SA = CLASS_SA.CLASS_CODE_SA
JOIN TEACHER_SA ON CLASS_SA.TEACHER_SA_ID_SA = TEACHER_SA.ID_SA
ORDER BY STUDENT_SA.FIRST_NAME_SA;

SELECT CLASS_SA.CLASS_CODE_SA AS Color,
STUDENT_SA.DATE_OF_BIRTH_SA AS 'Level',
STUDENT_SA.FIRST_NAME_SA AS 'Student Name',
STUDENT_SA.ZIPCODE_SA AS Zipcode
FROM STUDENT_SA
JOIN CLASS_SA ON STUDENT_SA.CLASS_CODE_SA = CLASS_SA.CLASS_CODE_SA
ORDER BY CLASS_SA.CLASS_CODE_SA, STUDENT_SA.FIRST_NAME_SA;

SELECT CARETAKER_SA.FIRST_NAME_SA,
CARETAKER_SA.LAST_NAME_SA,
CARETAKER_SA.PHONE_SA,
STUDENT_SA.FIRST_NAME_SA,
STUDENT_SA.LAST_NAME_SA,
STUDENT_SA.DATE_OF_BIRTH_SA,
CLASS_SA.CLASS_CODE_SA
FROM CARETAKER_SA
JOIN REGISTRATION_SA ON CARETAKER_SA.ID_SA = REGISTRATION_SA.CARETAKER_ID_SA
JOIN STUDENT_SA ON REGISTRATION_SA.STUDENT_ID_SA = STUDENT_SA.ID_SA
JOIN CLASS_SA ON STUDENT_SA.CLASS_CODE_SA = CLASS_SA.CLASS_CODE_SA
ORDER BY CARETAKER_SA.FIRST_NAME_SA, CARETAKER_SA.LAST_NAME_SA, STUDENT_SA.FIRST_NAME_SA;

SELECT
    CARETAKER_SA.FIRST_NAME_SA AS parent,
    TEACHER_SA.FIRST_NAME_SA AS teacher,
    STUDENT_SA.FIRST_NAME_SA AS student
FROM CARETAKER_SA
LEFT JOIN REGISTRATION_SA
    ON CARETAKER_SA.ID_SA = REGISTRATION_SA.CARETAKER_ID_SA
LEFT JOIN STUDENT_SA
    ON REGISTRATION_SA.STUDENT_ID_SA = STUDENT_SA.ID_SA
LEFT JOIN CLASS_SA
    ON STUDENT_SA.CLASS_CODE_SA = CLASS_SA.CLASS_CODE_SA
LEFT JOIN TEACHER_SA
    ON CLASS_SA.TEACHER_SA_ID_SA = TEACHER_SA.ID_SA
ORDER BY 
    CARETAKER_SA.FIRST_NAME_SA,
    TEACHER_SA.FIRST_NAME_SA,
    STUDENT_SA.FIRST_NAME_SA;